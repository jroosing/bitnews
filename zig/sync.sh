#!/bin/sh
# Copies the files the Go and the Zig versions share into zig/ (M15, ADR-0014):
# the SQL migrations, with a generated migrations.zig that embeds them. There is
# one source (internal/store/migrations); the copies exist because @embedFile
# cannot reach outside its module. `sync.sh` updates them, `sync.sh --check`
# fails when they differ from the sources.
set -eu
here=$(cd "$(dirname "$0")" && pwd)
src="$here/../internal/store/migrations"
dst="$here/migrations"

gen() { # prints migrations.zig for the .sql files in the directory $1
	echo '//! Generated by zig/sync.sh from internal/store/migrations. Do not edit.'
	echo 'pub const File = struct { name: []const u8, sql: []const u8 };'
	echo 'pub const files = [_]File{'
	for f in $(cd "$1" && ls *.sql | sort); do
		echo "    .{ .name = \"$f\", .sql = @embedFile(\"$f\") },"
	done
	echo '};'
}

case "${1:-}" in
--check)
	tmp=$(mktemp -d)
	trap 'rm -rf "$tmp"' EXIT
	cp "$src"/*.sql "$tmp/"
	gen "$tmp" >"$tmp/migrations.zig"
	if ! diff -r "$tmp" "$dst" >/dev/null 2>&1; then
		echo "zig/migrations is out of date (run zig/sync.sh)" >&2
		diff -r "$tmp" "$dst" >&2 || true
		exit 1
	fi
	echo "zig/migrations up to date"
	;;
"")
	rm -f "$dst"/*.sql "$dst"/migrations.zig
	cp "$src"/*.sql "$dst/"
	gen "$dst" >"$dst/migrations.zig"
	echo "synced $(ls "$dst"/*.sql | wc -l | tr -d ' ') migrations"
	;;
*)
	echo "usage: sync.sh [--check]" >&2
	exit 2
	;;
esac
