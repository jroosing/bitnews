#!/bin/sh
# Copies the files the Go and the Zig versions share into zig/ (M15, ADR-0014):
# the SQL migrations, with a generated migrations.zig that embeds them, and the
# NZB test fixtures of the parser. There is one source for each
# (internal/store/migrations, internal/usenet/nzb/testdata); the copies exist
# because @embedFile cannot reach outside its module. `sync.sh` updates them,
# `sync.sh --check` fails when they differ from the sources.
set -eu
here=$(cd "$(dirname "$0")" && pwd)
src="$here/../internal/store/migrations"
dst="$here/migrations"
nzb_src="$here/../internal/usenet/nzb/testdata"
nzb_dst="$here/src/nzb_testdata"

gen() { # prints migrations.zig for the .sql files in the directory $1
	echo '//! Generated by zig/sync.sh from internal/store/migrations. Do not edit.'
	echo 'pub const File = struct { name: []const u8, sql: []const u8 };'
	echo 'pub const files = [_]File{'
	for f in $(cd "$1" && ls *.sql | sort); do
		echo "    .{ .name = \"$f\", .sql = @embedFile(\"$f\") },"
	done
	echo '};'
}

case "${1:-}" in
--check)
	tmp=$(mktemp -d)
	trap 'rm -rf "$tmp"' EXIT
	cp "$src"/*.sql "$tmp/"
	gen "$tmp" >"$tmp/migrations.zig"
	if ! diff -r "$tmp" "$dst" >/dev/null 2>&1; then
		echo "zig/migrations is out of date (run zig/sync.sh)" >&2
		diff -r "$tmp" "$dst" >&2 || true
		exit 1
	fi
	if ! diff -r "$nzb_src" "$nzb_dst" >/dev/null 2>&1; then
		echo "zig/src/nzb_testdata is out of date (run zig/sync.sh)" >&2
		diff -r "$nzb_src" "$nzb_dst" >&2 || true
		exit 1
	fi
	echo "zig/migrations and zig/src/nzb_testdata up to date"
	;;
"")
	rm -f "$dst"/*.sql "$dst"/migrations.zig
	cp "$src"/*.sql "$dst/"
	gen "$dst" >"$dst/migrations.zig"
	echo "synced $(ls "$dst"/*.sql | wc -l | tr -d ' ') migrations"
	rm -rf "$nzb_dst"
	mkdir -p "$nzb_dst"
	cp "$nzb_src"/* "$nzb_dst/"
	echo "synced $(ls "$nzb_dst" | wc -l | tr -d ' ') nzb fixtures"
	;;
*)
	echo "usage: sync.sh [--check]" >&2
	exit 2
	;;
esac
