#!/usr/bin/env bash
# Regenerates internal/web/icons_gen.go from the Heroicons npm package (MIT,
# 24x24 outline set). The tarball is checked against the sha512 integrity that
# npm publishes. To add an icon, add "name=heroicon-file" to ICONS below and
# re-run; to bump Heroicons, change the version and integrity.
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
VERSION=2.2.0
INTEGRITY=sha512-yOwvztmNiBWqR946t+JdgZmyzEmnRMC2nxvHFC90bF1SUttwB6yJKYeme1JeEcBfobdOs827nCyiWBS2z/brog==

ICONS="
queue=arrow-down-tray
upload=arrow-up-tray
arrow-down=arrow-down
arrow-up=arrow-up
history=clock
settings=cog-6-tooth
menu=bars-3
close=x-mark
sun=sun
moon=moon
desktop=computer-desktop
sign-out=arrow-right-on-rectangle
user=user-circle
check=check
check-circle=check-circle
warning=exclamation-triangle
info=information-circle
error=x-circle
chevron-down=chevron-down
chevron-left=chevron-left
chevron-right=chevron-right
plus=plus
trash=trash
pause=pause
play=play
copy=clipboard-document
inbox=inbox
eye=eye
eye-slash=eye-slash
lock=lock-closed
key=key
search=magnifying-glass
more=ellipsis-horizontal
refresh=arrow-path
shield=shield-exclamation
server=server-stack
folder=folder
bolt=bolt
"

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
curl -fsSL --proto '=https' --tlsv1.2 "https://registry.npmjs.org/heroicons/-/heroicons-$VERSION.tgz" -o "$work/h.tgz"
got="sha512-$(openssl dgst -sha512 -binary "$work/h.tgz" | openssl base64 -A)"
[ "$got" = "$INTEGRITY" ] || { echo "integrity mismatch: $got" >&2; exit 1; }
tar -xzf "$work/h.tgz" -C "$work"
cp "$work/package/LICENSE" "$root/internal/web/assets/static/ICONS-LICENSE"

out="$root/internal/web/icons_gen.go"
{
	echo "// Code generated by scripts/gen-icons.sh from Heroicons $VERSION (MIT, see"
	echo "// assets/static/ICONS-LICENSE). DO NOT EDIT."
	echo
	echo "package web"
	echo
	echo "// iconPaths maps an icon name to the inner markup of its 24x24 outline SVG."
	echo "var iconPaths = map[string]string{"
	for spec in $ICONS; do
		name="${spec%%=*}"
		file="$work/package/24/outline/${spec#*=}.svg"
		inner="$(sed -e '1d;$d' "$file" | tr -d '\n' | sed -e 's/  */ /g' -e 's/^ //')"
		printf '\t"%s": `%s`,\n' "$name" "$inner"
	done
	echo "}"
} >"$out"
gofmt -s -w "$out"
echo "wrote $out"
